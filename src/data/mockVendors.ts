// ── Helper functions ──────────────────────────────────────────────────────────

export function getVendorsOpenNow(): Vendor[] {
  return MOCK_VENDORS.filter(v => isVendorOpenNow(v.openTime, v.closeTime));
}

export function getVendorsByCategory(category: string): Vendor[] {
  if (category === 'all') return MOCK_VENDORS;
  return MOCK_VENDORS.filter(v => v.category === category);
}

export function getLiveVendors(): Vendor[] {
  return MOCK_VENDORS.filter(v => v.isLive);
}

export function searchVendors(query: string): Vendor[] {
  const q = query.toLowerCase().trim();
  if (!q) return MOCK_VENDORS;
  return MOCK_VENDORS.filter(v =>
    v.name.toLowerCase().includes(q) ||
    v.subcategory.toLowerCase().includes(q) ||
    v.description.toLowerCase().includes(q) ||
    v.tags.some(t => t.toLowerCase().includes(q))
  );
}

export function getVendorsByLocality(locality: string): Vendor[] {
  return MOCK_VENDORS.filter(v => v.locality.toLowerCase() === locality.toLowerCase());
}

export function getNearbyVendors(maxKm = 1.0): Vendor[] {
  return MOCK_VENDORS.filter(v => v.distance <= maxKm).sort((a, b) => a.distance - b.distance);
}

export function getTopPickVendors(): Vendor[] {
  return MOCK_VENDORS
    .filter(v => v.isVerified && v.rating >= 4.4)
    .sort((a, b) => b.rating - a.rating)
    .slice(0, 6);
}

export function getLiveStats(): LSIData {
  const openNow = getVendorsOpenNow().length;
  const liveNow = getLiveVendors().length;
  const score = Math.round(Math.min(100, (openNow / MOCK_VENDORS.length) * 100 + liveNow * 5));
  return {
    score,
    vendorsActive: openNow,
    openNow,
    liveNow,
    avgResponseTime: '8 min',
    locality: 'Patuli',
  };
}
